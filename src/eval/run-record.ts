import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Answers, ChoiceAnswer, Usage } from '../typesafe/client.js';
import type { ProviderName } from '../typesafe/index.js';
import type { CascadeResult } from '../checkout/cascade.js';
import type { FinalAction, Stage1Route } from '../checkout/decide.js';
import type { TriageAction, TriageDecision } from '../triage/decide.js';

/**
 * The run record: the atomic unit of every eval and claim test on access day.
 * One record = one provider answering one fixture once, with the full typed
 * answers preserved verbatim so every downstream metric (pass/fail, Brier/ECE,
 * latency, cost, schema violations, agreement) can be computed post-hoc from
 * the persisted JSON, never re-derived from stdout.
 *
 * Persistence layout (all committed to git; no secrets by construction):
 *   results/<YYYY-MM-DD>/run-<provider>-<domain>-run<index>.json
 *   results/<YYYY-MM-DD>/results.csv   (flat rows for external plotting)
 *   results/<YYYY-MM-DD>/report.md     (generated by the eval CLI)
 */

export const RUN_RECORD_SCHEMA_VERSION = 1 as const;

export type EvalDomain = 'triage' | 'checkout';

/** Which model produced the record, for time-series comparison across versions. */
export interface ModelMetadata {
  /** Model id: OLLAMA_MODEL for llm, 'jev-latest' for real, 'mock' for mock. */
  model: string;
  /** API base when relevant (llm provider). */
  baseUrl?: string;
  /** Self-consistency sample count (llm provider only). */
  samples?: number;
}

interface RunRecordCommon {
  schemaVersion: number;
  /** 0-based run index within one eval invocation (--runs=K). */
  runIndex: number;
  provider: ProviderName;
  scenario: string;
  /** ISO 8601 UTC moment the answer was produced. */
  timestamp: string;
  model: ModelMetadata;
  /** Total usage across all stages (checkout adds stage 1 + stage 3 + bureau). */
  usage: Usage;
  /** Confidence of the answer that drove the decision. */
  confidence: number;
}

export interface TriageRunRecord extends RunRecordCommon {
  domain: 'triage';
  action: TriageAction;
  answers: Answers;
}

export interface CheckoutRunRecord extends RunRecordCommon {
  domain: 'checkout';
  stage1Route: Stage1Route;
  bureauCalled: boolean;
  finalAction: FinalAction | null;
  stage1Answers: Answers;
  stage3Answers: Answers | null;
  bureauLatencyMs: number | null;
  pFraudEstimate: number | null;
  evApproveUsd: number | null;
}

export type RunRecord = TriageRunRecord | CheckoutRunRecord;

export interface RunRecordInput {
  provider: ProviderName;
  scenario: string;
  runIndex: number;
  model: ModelMetadata;
  /** Overridable for deterministic tests; defaults to now. */
  timestamp?: string;
}

/** The answer the routing decision hinged on: failure_category for triage. */
export function triagePrimaryConfidence(answers: Answers): number {
  const category = answers['failure_category'] as ChoiceAnswer | undefined;
  return category?.confidence ?? 0;
}

/** final_action when the bureau ran; risk_band on the stage-1 fast paths. */
export function checkoutPrimaryConfidence(
  stage1: Answers,
  stage3: Answers | null,
): number {
  const finalAction = stage3?.['final_action'] as ChoiceAnswer | undefined;
  const riskBand = stage1['risk_band'] as ChoiceAnswer | undefined;
  return finalAction?.confidence ?? riskBand?.confidence ?? 0;
}

export function buildTriageRunRecord(
  input: RunRecordInput,
  decision: TriageDecision,
  answers: Answers,
  usage: Usage,
): TriageRunRecord {
  return {
    schemaVersion: RUN_RECORD_SCHEMA_VERSION,
    domain: 'triage',
    runIndex: input.runIndex,
    provider: input.provider,
    scenario: input.scenario,
    timestamp: input.timestamp ?? new Date().toISOString(),
    model: input.model,
    action: decision.action,
    answers,
    confidence: triagePrimaryConfidence(answers),
    usage,
  };
}

export function buildCheckoutRunRecord(
  input: RunRecordInput,
  result: CascadeResult,
): CheckoutRunRecord {
  const stage3 = result.stage3Usage;
  const bureauLatency = result.bureauLatencyMs ?? 0;
  const usage: Usage = {
    inputTokens: result.stage1Usage.inputTokens + (stage3?.inputTokens ?? 0),
    outputTokens: result.stage1Usage.outputTokens + (stage3?.outputTokens ?? 0),
    calls: result.stage1Usage.calls + (stage3?.calls ?? 0),
    elapsedMs: result.stage1Usage.elapsedMs + (stage3?.elapsedMs ?? 0) + bureauLatency,
  };
  return {
    schemaVersion: RUN_RECORD_SCHEMA_VERSION,
    domain: 'checkout',
    runIndex: input.runIndex,
    provider: input.provider,
    scenario: input.scenario,
    timestamp: input.timestamp ?? new Date().toISOString(),
    model: input.model,
    stage1Route: result.stage1Route,
    bureauCalled: result.bureauCalled,
    finalAction: result.finalAction,
    stage1Answers: result.stage1Answers,
    stage3Answers: result.stage3Answers,
    bureauLatencyMs: result.bureauLatencyMs,
    pFraudEstimate: result.pFraudEstimate,
    evApproveUsd: result.evApproveUsd,
    confidence: checkoutPrimaryConfidence(result.stage1Answers, result.stage3Answers),
    usage,
  };
}

// ── persistence ───────────────────────────────────────────────────────────────

export function resultsDirFor(date: Date = new Date(), baseDir = 'results'): string {
  return join(baseDir, date.toISOString().slice(0, 10));
}

export function ensureResultsDir(date: Date = new Date(), baseDir = 'results'): string {
  const dir = resultsDirFor(date, baseDir);
  mkdirSync(dir, { recursive: true });
  return dir;
}

export function runFileName(
  provider: ProviderName,
  domain: EvalDomain,
  runIndex: number,
): string {
  return `run-${provider}-${domain}-run${runIndex}.json`;
}

export interface RunFilePayload {
  schemaVersion: number;
  provider: ProviderName;
  domain: EvalDomain;
  runIndex: number;
  model: ModelMetadata;
  records: RunRecord[];
}

export function writeRunFile(dir: string, payload: RunFilePayload): string {
  const file = join(
    dir,
    runFileName(payload.provider, payload.domain, payload.runIndex),
  );
  writeFileSync(file, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  return file;
}

export const CSV_HEADER = [
  'run_index',
  'timestamp',
  'provider',
  'domain',
  'scenario',
  'action',
  'stage1_route',
  'bureau_called',
  'confidence',
  'latency_ms',
  'calls',
  'input_tokens',
  'output_tokens',
  'model',
] as const;

function csvCell(value: string): string {
  return /[",\n]/.test(value) ? `"${value.replaceAll('"', '""')}"` : value;
}

function csvRow(record: RunRecord): string[] {
  const common = [
    String(record.runIndex),
    record.timestamp,
    record.provider,
    record.domain,
    record.scenario,
  ];
  if (record.domain === 'triage') {
    return [
      ...common,
      record.action,
      '',
      '',
      record.confidence.toFixed(3),
      String(record.usage.elapsedMs),
      String(record.usage.calls),
      String(record.usage.inputTokens),
      String(record.usage.outputTokens),
      record.model.model,
    ];
  }
  return [
    ...common,
    record.finalAction ?? '',
    record.stage1Route,
    String(record.bureauCalled),
    record.confidence.toFixed(3),
    String(record.usage.elapsedMs),
    String(record.usage.calls),
    String(record.usage.inputTokens),
    String(record.usage.outputTokens),
    record.model.model,
  ];
}

export function toCsv(records: readonly RunRecord[]): string {
  const rows = records.map((record) => csvRow(record).map(csvCell).join(','));
  return `${[CSV_HEADER.join(','), ...rows].join('\n')}\n`;
}

export function writeCsvFile(dir: string, records: readonly RunRecord[]): string {
  const file = join(dir, 'results.csv');
  writeFileSync(file, toCsv(records), 'utf8');
  return file;
}